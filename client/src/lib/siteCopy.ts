export function localizeProject(project: any, locale: Locale) {
  if (!project) return project;
  const isArabic = locale === "ar";
  const projectArabicTitles: Record<string, string> = {
    "ERA shopping Logo & Brand": "هوية وشعار متجر إيرا للتسوق",
    "Jenan Yemeni Honey Logo Branding": "هوية عسل جنان اليمن",
    "Ekleel Alenayah Medical Company Logo Brand": "هوية شركة إكليل العناية الطبية",
    "Caesar logo & Brand": "هوية وشعار قيصر",
    "AL-KHATTABI PRESS LOGO & IDENTITY": "شعار وهوية مطابع الخطابي",
    "Balsam Taibah Medical Co. Logo & Branding": "هوية شركة بلسم طابة الطبية",
    "Al-Bakeli Dental Clinic": "هوية عيادة البكيلي للأسنان",
    "Baha’a Silver Logo - typography": "شعار بهاء سيلفر والخط العربي",
  };
  const fallbackTitle = isArabic ? projectArabicTitles[project.title] || project.title : project.title;
  const fallbackCategory = isArabic ? "هوية بصرية" : project.category;
  const fallbackDescription = isArabic ? "مشروع هوية بصرية يجمع بين الفكرة الواضحة والتطبيقات المدروسة." : project.description;
  const slideTitles = ["01 / الشعار والفكرة الرئيسية", "02 / تطبيقات الهوية", "03 / التفاصيل واللغة البصرية", "04 / العرض النهائي"];
  const slideDescriptions = ["تكوين بصري واضح يرسخ شخصية المشروع من أول نظرة.", "تنتقل الهوية إلى التطبيقات اليومية مع الحفاظ على اتساقها.", "تفاصيل مدروسة تمنح النظام مرونة وحضوراً مميزاً.", "منظومة متكاملة جاهزة للاستخدام عبر مختلف نقاط التواصل."];
  return {
    ...project,
    title: (isArabic ? project.titleAr : project.titleEn) || fallbackTitle,
    category: (isArabic ? project.categoryAr : project.categoryEn) || fallbackCategory,
    description: (isArabic ? project.descriptionAr : project.descriptionEn) || fallbackDescription,
    slides: project.slides?.map((slide: any, index: number) => ({
      ...slide,
      title: (isArabic ? slide.titleAr : slide.titleEn) || (isArabic ? slideTitles[index] || `0${index + 1} / مرحلة من الهوية` : slide.title),
      description: (isArabic ? slide.descriptionAr : slide.descriptionEn) || (isArabic ? slideDescriptions[index] || "تطبيق بصري مدروس ضمن منظومة المشروع." : slide.description),
    })),
  };
}

export function localizePost(post: any, locale: Locale) {
  if (!post) return post;
  return {
    ...post,
    title: (locale === "ar" ? post.titleAr : post.titleEn) || post.title,
    summary: (locale === "ar" ? post.summaryAr : post.summaryEn) || post.summary,
    content: (locale === "ar" ? post.contentAr : post.contentEn) || post.content,
  };
}

export function localizeSection(section: any, locale: Locale) {
  if (!section) return section;
  return {
    ...section,
    title: (locale === "ar" ? section.titleAr : section.titleEn) || section.title,
    subtitle: (locale === "ar" ? section.subtitleAr : section.subtitleEn) || section.subtitle,
    content: (locale === "ar" ? section.contentAr : section.contentEn) || section.content,
  };
}
